"""Scene renderers (the 'video generation' providers of the zero-cost route).

threejs: deterministic procedural 3D, rendered frame-by-frame in headless Chromium (software WebGL).
mock:    flat coloured frames generated by FFmpeg (tests / CI smoke runs; no browser needed)."""
from __future__ import annotations

import base64
import json
import shutil
from pathlib import Path

from . import ProviderInfo, ProviderUnavailable, register
from ..util import ENGINE_DIR, FFMPEG, run

THREE_DIR = ENGINE_DIR / "three"


def module_url(module: str) -> str:
    """'scenes/s1.js' -> '/project/scenes/s1.js' ; 'builtin:endcard' -> '/engine/builtin/endcard.js'"""
    if module.startswith("builtin:"):
        return f"/engine/builtin/{module.split(':', 1)[1]}.js"
    return "/project/" + module.lstrip("/")


@register("renderer", "threejs")
class ThreeRenderer:
    def __init__(self, timeout_s: float = 7200, **_: object) -> None:
        self.info = ProviderInfo("renderer", "threejs", paid=False, model="three.js r170 + Chromium SwiftShader", license="MIT (three.js)")
        self.timeout = timeout_s

    def check(self) -> list[str]:
        problems = []
        if not shutil.which("node"):
            problems.append("node (Node.js >= 18) not found on PATH")
        if not (THREE_DIR / "node_modules" / "three").is_dir():
            problems.append("engine/three/node_modules missing: run `npm ci` in engine/three")
        if not (THREE_DIR / "node_modules" / "playwright").exists():
            problems.append("playwright not resolvable from engine/three (npm ci, or link a preinstalled playwright)")
        return problems

    def render(self, *, project_dir: Path, module: str, dur: float, fps: int, width: int, height: int,
               params: dict, out_dir: Path, start: int = 0, log=None) -> None:
        if self.check():
            raise ProviderUnavailable("; ".join(self.check()))
        cmd = ["node", str(THREE_DIR / "render.mjs"), "--module", module_url(module), "--project", str(project_dir),
               "--dur", f"{dur:.4f}", "--fps", str(fps), "--w", str(width), "--h", str(height), "--out", str(out_dir),
               "--start", str(start)]
        if params:
            cmd += ["--params", base64.b64encode(json.dumps(params).encode()).decode()]
        run(cmd, log=log, timeout=self.timeout)


@register("renderer", "mock")
class MockRenderer:
    def __init__(self, **_: object) -> None:
        self.info = ProviderInfo("renderer", "mock", paid=False, model="ffmpeg testsrc", license="n/a (test only)")

    def check(self) -> list[str]:
        return [] if shutil.which("ffmpeg") else ["ffmpeg not found"]

    def render(self, *, project_dir: Path, module: str, dur: float, fps: int, width: int, height: int,
               params: dict, out_dir: Path, start: int = 0, log=None) -> None:
        out_dir.mkdir(parents=True, exist_ok=True)
        n = round(dur * fps)
        hue = sum(module.encode()) % 360
        run(FFMPEG + ["-f", "lavfi", "-i", f"testsrc2=s={width}x{height}:r={fps}:d={dur:.4f}",
                      "-vf", f"hue=h={hue}", "-frames:v", str(n), "-start_number", "0", str(out_dir / "f%04d.png")], log=log)
